import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const read = (file) => fs.readFileSync(path.join(root, file), "utf8");
const lock = JSON.parse(read("package-lock.json"));
// These npm archives omit their license files. Preserve upstream copies locally.
const fallback = {
  "@ant-design/icons-svg": ["licenses/ant-design-icons-LICENSE"],
  "@ant-design/icons-vue": ["licenses/ant-design-icons-LICENSE"],
  "array-tree-filter": ["licenses/array-tree-filter-LICENSE"],
  "dom-scroll-into-view": ["licenses/dom-scroll-into-view-NOTICE"],
};
const sections = [];
for (const [directory, entry] of Object.entries(lock.packages).sort(
  ([a], [b]) => a.localeCompare(b, "en"),
)) {
  if (!directory || entry.dev) continue;
  const absolute = path.join(root, directory);
  if (!fs.existsSync(absolute) && entry.optional) continue;
  const pkg = JSON.parse(read(`${directory}/package.json`));
  if (pkg.version !== entry.version)
    throw new Error(`Installed version differs from lockfile: ${pkg.name}`);
  let files = fs
    .readdirSync(absolute, { withFileTypes: true })
    .filter(
      (file) =>
        file.isFile() &&
        /^(licen[sc]e|copying|notice)(?:$|[._-])/i.test(file.name),
    )
    .map((file) => `${directory}/${file.name}`)
    .sort();
  if (!files.length) files = fallback[pkg.name] || [];
  if (!files.length && pkg.name.startsWith("@rolldown/binding-"))
    files = ["node_modules/rolldown/LICENSE"];
  if (!files.length) throw new Error(`Missing license text: ${pkg.name}`);
  const repository =
    typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  sections.push(
    [
      `${pkg.name}@${pkg.version}`,
      `Declared license: ${pkg.license || entry.license || "See license text"}`,
      `Source: ${repository || pkg.homepage || entry.resolved || directory}`,
      ...files.map((file) => `\n--- ${file} ---\n${read(file).trim()}`),
    ].join("\n"),
  );
}
const electron = JSON.parse(read("node_modules/electron/package.json"));
sections.push(
  `Electron ${electron.version}\nSource: https://github.com/electron/electron\n\n${read("node_modules/electron/dist/LICENSE").trim()}\n\nChromium and other Electron component notices accompany the Electron distribution in LICENSES.chromium.html.`,
);
const text = [
  "BaiduPCS-Desktop - third-party dependency notices",
  "Generated by npm run licenses:generate from installed lockfile dependencies.",
  "Includes non-development npm dependencies present on the build platform and Electron; some packages may be removed by bundling.",
  "Upstream license texts are reproduced below. BaiduPCS-Rust and artwork are covered separately in THIRD_PARTY_NOTICES.md.",
  ...sections.map((section) => `\n${"=".repeat(80)}\n${section}`),
  "",
]
  .join("\n")
  .replace(/\r\n/g, "\n")
  .replace(/[\t ]+$/gm, "");
fs.mkdirSync(path.join(root, "licenses"), { recursive: true });
fs.writeFileSync(path.join(root, "licenses/npm-THIRD-PARTY-NOTICES.txt"), text);
console.log(`Generated notices for ${sections.length} dependency entries.`);
